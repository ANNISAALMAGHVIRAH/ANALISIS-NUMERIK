#Algoritma1
#Step 1: input awal adalah angka yang paling besar
x_awal1 = 10000.0

#Step 2: input awal adalah angka yang paling kecil
x_selanjutnya1 = 0.0001

#Step 3: melakukan perulangan
for _ in range(5):
  x_awal1 += x_selanjutnya1

#cetak hasil
print("Hasil penjumlahan algoritma 1 adalah", x_awal1)






